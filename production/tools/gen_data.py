"""Generate the data the animation page and the mix need.

- animation/timing.js : voice word timings (video time), caption cues, cue list
- animation/icons.js  : Font Awesome path data used on screen
- output SRT          : captions retimed to the supplied voiceover

All times are in video seconds. The voiceover is placed VO_OFFSET seconds
into the video so the voice starts once the intro title has landed.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(ROOT)

VO_OFFSET = 0.80          # voice starts at 0:00.9, as in the storyboard
HOLD_AFTER_VOICE = 1.0    # hold the last frame one second after the voice ends
FPS = 30


def load_words():
    d = json.load(open(os.path.join(ROOT, "data", "voice_words.json")))
    lines = d["lines"]
    words = [dict(w, start=round(w["start"] + VO_OFFSET, 3), end=round(w["end"] + VO_OFFSET, 3)) for w in d["words"]]
    return lines, words


def caption_cues(lines, words, video_end):
    cues = []
    for li, text in enumerate(lines):
        ws = [w for w in words if w["line"] == li]
        cues.append({"text": text, "start": ws[0]["start"] - 0.10, "end": ws[-1]["end"] + 0.30})
    for i in range(len(cues) - 1):
        nxt = cues[i + 1]["start"]
        if nxt - cues[i]["end"] < 0.5 or cues[i]["end"] > nxt:
            cues[i]["end"] = nxt          # contiguous: swap without a gap
    # last line: keep it up for half a second after the voice, leave a clean end card
    cues[-1]["end"] = min(video_end - 0.35, words[-1]["end"] + 0.5)
    for c in cues:
        c["start"] = round(max(0.0, c["start"]), 3)
        c["end"] = round(c["end"], 3)
    return cues


def srt_time(t):
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3600000)
    m, ms = divmod(ms, 60000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def icons():
    out = {}
    d = os.path.join(ROOT, "animation", "assets", "icons")
    for f in sorted(os.listdir(d)):
        if not f.endswith(".svg"):
            continue
        s = open(os.path.join(d, f)).read()
        vb = re.search(r'viewBox="([^"]+)"', s).group(1)
        path = re.search(r'<path d="([^"]+)"', s).group(1)
        out[f[:-4]] = {"vb": vb, "d": path}
    return out


def main():
    lines, words = load_words()
    video_end = round(words[-1]["end"] + HOLD_AFTER_VOICE, 1)
    nframes = int(round(video_end * FPS))
    video_end = nframes / FPS
    cues = caption_cues(lines, words, video_end)

    timing = {
        "fps": FPS,
        "duration": video_end,
        "frames": nframes,
        "voOffset": VO_OFFSET,
        "lines": lines,
        "words": words,
        "captions": cues,
    }
    with open(os.path.join(ROOT, "animation", "timing.js"), "w") as f:
        f.write("// generated by tools/gen_data.py - do not edit\n")
        f.write("window.TIMING = " + json.dumps(timing, indent=1) + ";\n")
    with open(os.path.join(ROOT, "animation", "icons.js"), "w") as f:
        f.write("// generated by tools/gen_data.py from Font Awesome Free 6.5.2 (CC BY 4.0 icons)\n")
        f.write("window.ICONS = " + json.dumps(icons()) + ";\n")
    json.dump(timing, open(os.path.join(ROOT, "data", "timing.json"), "w"), indent=1)

    out_dir = os.path.join(REPO, "output")
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "HOME-07_DoINeedAIForThis_captions_EN_v2.srt"), "w") as f:
        for i, c in enumerate(cues, 1):
            f.write(f"{i}\n{srt_time(c['start'])} --> {srt_time(c['end'])}\n{c['text']}\n\n")
    print(f"duration {video_end:.3f}s, {nframes} frames, {len(cues)} captions")


if __name__ == "__main__":
    main()
